import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';
const root=fileURLToPath(new URL('../',import.meta.url));
const load=p=>readFileSync(new URL(p,root),'utf8');
const source=load('src/radio-upload-security.ts');
const js=ts.transpileModule(source.replace(/^export /gm,''),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.None}}).outputText;
const {validRadioObjectKey,validRadioRetentionHours}=runInNewContext(js+';({validRadioObjectKey,validRadioRetentionHours})',{});
for(const key of ['radio/2026/prayer-01.mp3','broadcast audio/teaching (1).m4a','radio/gospel_track.flac'])assert.equal(validRadioObjectKey(key),true,key);
for(const key of ['/radio/file.mp3','radio/../file.mp3','radio//file.mp3','radio/file.mp3?x=1','radio/file#1.mp3','radio/file\\name.mp3','radio/./file.mp3','radio/%2e%2e/a.mp3','radio/ file.mp3','radio/file.mp3/',''])assert.equal(validRadioObjectKey(key),false,key);
for(const n of [1,48,8760])assert.equal(validRadioRetentionHours(n),true);
for(const n of [0,-1,8761,1.4,NaN,Infinity,'48',null])assert.equal(validRadioRetentionHours(n),false);
const index=load('src/index.ts');
assert.ok(index.includes('validRadioObjectKey(objectKey)'),'Register must validate object keys');
assert.ok(index.includes('validRadioRetentionHours(b.retention_hours??48)'),'Register must validate retention');
assert.ok(index.includes('SELECT media_id FROM media_objects WHERE object_key=? LIMIT 1'),'Prevent existing DB key collision');
assert.ok(index.includes('await env.MEDIA_R2.head(objectKey)'),'Prevent overwriting existing R2 object');
assert.ok(index.includes("AND media_type='audio' ORDER BY created_at DESC LIMIT 50"),'Mask TV asset list');
assert.ok(index.includes("WHERE channel='radio'"),'Mask TV settings');
assert.ok(index.includes("if(TV_LOCKED&&row.media_type!=='audio')return tvLockedResponse()"),'Lock legacy video upload hints');
console.log('Account 2 audio storage key, duplicate reuse, retention and TV visibility security tests passed');
