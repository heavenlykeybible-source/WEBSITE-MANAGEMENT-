import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';

const root=fileURLToPath(new URL('../',import.meta.url));
const load=p=>readFileSync(resolve(root,p),'utf8');
const lock=load('src/channel-lock.ts');
const index=load('src/index.ts');
const broadcast=load('src/public-broadcast.ts');
const restream=load('src/restream.ts');
const transpiled=ts.transpileModule(lock.replace(/^export /gm,''),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.None}}).outputText;
const lockExports=runInNewContext(transpiled+';({TV_LOCKED,TV_LOCK_MESSAGE,channelAvailability,tvLockedResponse})',{Response});
assert.equal(lockExports.TV_LOCKED,true);
const availability=lockExports.channelAvailability();
assert.equal(availability.radio.locked,false,'Radio must remain enabled');
assert.equal(availability.radio.available,true);
assert.equal(availability.television.locked,true,'TV must be locked');
assert.equal(availability.television.available,false);
const lockedResponse=lockExports.tvLockedResponse();
assert.equal(lockedResponse.status,423);
assert.equal((await lockedResponse.json()).code,'TELEVISION_LOCKED');
assert.ok(index.includes("url.pathname==='/api/broadcast/channel-availability'"),'Public availability endpoint is required');
assert.ok(index.includes("if(TV_LOCKED&&destination!=='radio')return tvLockedResponse()"),'Video and both destinations must be blocked');
assert.ok(index.includes("if(TV_LOCKED&&String(b.channel??'video')!=='radio')return tvLockedResponse()"),'TV social egress must be blocked');
assert.ok(index.includes("if(TV_LOCKED&&channel==='video')return tvLockedResponse()"),'TV playlist changes must be blocked');
assert.ok(index.includes("if(TV_LOCKED&&b?.channel==='video')return tvLockedResponse()"),'TV playlist settings must be blocked');
assert.ok(index.includes("if(TV_LOCKED&&mr.media_type==='video')return tvLockedResponse()"),'Video playout scheduling must be blocked');
assert.ok(restream.includes("if(TV_LOCKED&&input.channel!=='radio')"),'Core egress layer must block TV independently of the HTTP route');
assert.ok(broadcast.includes("if(channel==='video'&&TV_LOCKED)"),'Public TV programme must return locked status');
assert.ok(broadcast.includes("if(TV_LOCKED&&!adminPreview&&media.media_type==='video')"),'TV public video files must be blocked while editing previews remain available');
assert.ok(broadcast.includes("channel==='audio'?'radio':'video'"),'Audio radio routing must remain intact');
console.log('Account 2 television locked; radio availability and backend enforcement checks passed');
