import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';

const root=fileURLToPath(new URL('../',import.meta.url));
const load=path=>readFileSync(resolve(root,path),'utf8');
const source=load('src/radio-on-demand.ts');
const compiled=ts.transpileModule(source.replace(/^export /gm,''),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.None}}).outputText;
const meta=runInNewContext(compiled+';onDemandRadioMetadata()',{}); 
assert.equal(meta.delivery,'listener-activated');
assert.equal(meta.listenerStartsPlayback,true);
assert.equal(meta.alwaysOnEncoderRequired,false);
assert.equal(meta.standbyComputeRequired,false);
assert.equal(meta.loopPlaylist,true);
assert.equal(meta.nextTrackTrigger,'ended');
assert.equal(meta.audioFetch,'on-demand-range');
assert.equal(meta.synchronizedListeners,false);
const broadcast=load('src/public-broadcast.ts');
const index=load('src/index.ts');
assert.ok(broadcast.includes("import { onDemandRadioMetadata } from './radio-on-demand'"));
assert.ok(broadcast.includes("channel==='audio'?{...data,playback:onDemandRadioMetadata()}:data"),'Radio responses must advertise on-demand delivery');
assert.ok(broadcast.includes("AND (destination=? OR (destination='both' AND ?='video'))"),'Radio must ignore television-only and mixed live sessions');
assert.ok(broadcast.includes(".bind(channel==='audio'?'radio':'video',channel).first<any>()"),'Live channel restriction must use bound parameters');
assert.ok(broadcast.includes('return reply({mode:entries.length?'), 'Playlist must supply listener-activated contract');
assert.ok(broadcast.includes("const listenerOnly=channel==='audio'"),'Only radio permits on-demand mode');
assert.ok(broadcast.includes("AND ((l.destination='radio' AND m.media_type='audio') OR (?=0 AND l.destination IN ('video','both')))"),'TV-only live sessions must not authorize public radio media while TV is locked');
assert.ok(broadcast.includes("p.media_id=m.media_id AND (m.media_type='audio' OR ?=0)"),'Scheduled programmes must not expose unpublished non-audio assets while television is locked');
assert.ok(broadcast.includes('.bind(id,TV_LOCKED?1:0,TV_LOCKED?1:0).first()'),'TV restriction must use a bound database condition');
assert.ok(broadcast.includes('if(!listenerOnly&&live&&'),'On-demand playlists bypass legacy live takeover');
assert.ok(broadcast.includes('const live=listenerOnly?null:await env.DB.prepare'),'On-demand radio must skip unnecessary live-session database reads');
assert.ok(broadcast.includes('const scheduled=listenerOnly?null:await env.DB.prepare'),'On-demand radio must skip unnecessary scheduled playout reads');
assert.ok(broadcast.includes('if(!listenerOnly&&scheduled)return'),'On-demand playlists bypass fixed scheduled takeover');
assert.ok(broadcast.includes("const object=request.method==='HEAD'?head:await env.MEDIA_R2.get"),'Audio must be loaded only on listener request');
assert.ok(broadcast.includes("'Accept-Ranges':'bytes'"),'Seek/range audio delivery must remain available');
assert.ok(index.includes("if(TV_LOCKED&&destination!=='radio')return tvLockedResponse()"),'Television must remain locked');
console.log('Account 2 listener-activated radio on-demand metadata and audio delivery checks passed');
