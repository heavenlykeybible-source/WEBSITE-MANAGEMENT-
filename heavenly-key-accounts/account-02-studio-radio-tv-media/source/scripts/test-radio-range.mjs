import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';
const root=fileURLToPath(new URL('../',import.meta.url));
const load=p=>readFileSync(resolve(root,p),'utf8');
const compiled=ts.transpileModule(load('src/radio-byte-range.ts').replace(/^export /gm,''),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.None}}).outputText;
const parse=runInNewContext(compiled+';parseAudioRange',{Number,Math});
const check=(header,size,expected)=>assert.equal(JSON.stringify(parse(header,size)),JSON.stringify(expected),String(header));
check(null,100,null);
check('bytes=0-',100,{offset:0,length:100});
check('bytes=20-39',100,{offset:20,length:20});
check('bytes=98-200',100,{offset:98,length:2});
check('bytes=-10',100,{offset:90,length:10});
check('bytes=-200',100,{offset:0,length:100});
for(const invalid of ['bytes=100-','bytes=10-9','bytes=-0','bytes=','bytes=1-2,5-6','items=1-2','bytes=-1-2','bytes=1-99999999999999999999'])check(invalid,100,false);
check('bytes=0-',0,false);
const broadcast=load('src/public-broadcast.ts');
assert.ok(broadcast.includes('parseAudioRange(radioCanResumeRange(ifRange,head.httpEtag)?requestedRange:null,head.size)'),'Audio seek requests must honor If-Range');
assert.ok(broadcast.includes("status:416"));
assert.ok(broadcast.includes("const status=range?206:200"));
assert.ok(broadcast.includes("radioNotModified(ifNoneMatch,head.httpEtag)"),'Conditional validators must be checked');
assert.ok(broadcast.includes("status:304"),'Matching ETag must return 304');
assert.ok(broadcast.includes("request.method==='HEAD'?null"));
assert.ok(broadcast.includes("'Content-Range'"));
console.log('Account 2 radio byte seeking, suffix, invalid ranges and HEAD responses passed');
