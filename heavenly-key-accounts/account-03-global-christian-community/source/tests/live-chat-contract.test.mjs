import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL(p,import.meta.url),'utf8');
const html=read('../public/messages.html'),legacy=read('../public/community-live-chat.js');
assert.doesNotMatch(html,/<script[^>]+src="community-live-chat\.js/);
let calls=0;
const forbidden=()=>{calls++;throw Error('Legacy messenger must not run')};
vm.runInNewContext(legacy,{fetch:forbidden,document:new Proxy({},{get:forbidden}),setInterval:forbidden,setTimeout:forbidden});
assert.equal(calls,0,'Cached pages cannot mount a competing messenger or call obsolete APIs');
console.log('PASS cached and current pages use one messaging implementation');
