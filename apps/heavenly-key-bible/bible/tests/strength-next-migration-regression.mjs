import assert from 'node:assert/strict';
import {migrateLegacyEntry,migrateLegacyBatch} from './strength-next-migration.mjs';
import {validateDailyDevotional,SECTION_KEYS} from './strength-next-content-contract.mjs';
const topics=Array.from({length:12},(_,i)=>({topic:'Theme '+(i+1),reference:'Psalm 85:6',reflection:'Editorial source reflection '+(i+1),bibleText:'Existing unverified KJV quotation '+(i+1),prayer:'Existing prayer '+(i+1)}));
const legacy={date:'2026-10-30',title:'Return to Your First Love',scripture:'Revelation 2:4-5',reflection:'Return to Christ.',prayer:'Original central prayer',topics};
const before=JSON.stringify(legacy);
const draft=migrateLegacyEntry(legacy);
assert.equal(JSON.stringify(legacy),before,'legacy source must remain unchanged');
assert.equal(draft.status,'draft');
assert.equal(draft.sections.topic.title,legacy.title);
assert.equal(draft.sections.challenges.length,12);
assert.equal(draft.provenance.sourceMaterial.centralPrayer,legacy.prayer);
assert.equal(draft.provenance.sourceMaterial.originalTopicMaterials.length,12);
assert.equal(draft.provenance.sourceMaterial.originalTopicMaterials[0].prayer,topics[0].prayer);
assert.equal(draft.provenance.sourceMaterial.originalTopicMaterials[11].bibleText,topics[11].bibleText);
assert.equal(draft.provenance.requiresScriptureVerification,true);
assert.deepEqual(Object.keys(draft.sections),SECTION_KEYS);
assert.equal(draft.sections.worldStory,null,'never invent world stories');
assert.equal(draft.sections.hymn,null,'never invent hymn numbers');
assert.equal(draft.review.doctrinalApproved,false);
assert.ok(validateDailyDevotional(draft).length>0,'incomplete draft must never be publishable');
assert.throws(()=>migrateLegacyEntry({...legacy,topics:topics.slice(1)}),/twelve/);
assert.throws(()=>migrateLegacyEntry({...legacy,topics:topics.map(t=>({...t,topic:'Repeated'}))}),/Duplicate/);
assert.throws(()=>migrateLegacyBatch({entries:[legacy,legacy]}),/Duplicate devotional date/);
assert.equal(migrateLegacyBatch({entries:[legacy]}).length,1);
const missingDatePlaceholder={date:'2031-10-30',title:'EDITORIAL AUTHORING REQUIRED — NOT FOR PUBLICATION',scripture:'',reflection:'',prayer:'',status:'draft-not-published',topics:topics.map(t=>({topic:t.topic,reference:'',bibleText:'',reflection:'',prayer:'',reviewStatus:'draft-original-editorial-and-doctrinal-approval-pending'}))};
assert.equal(migrateLegacyBatch({entries:[legacy,missingDatePlaceholder]}).length,1,'Unwritten calendar placeholders must remain missing drafts, not become content');
assert.throws(()=>migrateLegacyEntry(missingDatePlaceholder),/Incomplete legacy topic/,'An unwritten placeholder must never be migrated as a devotional');
console.log('One-topic migration and draft safety regression checks passed');
