import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const worker=fs.readFileSync(new URL('./worker.mjs',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('./editor.html',import.meta.url),'utf8');
const schema=fs.readFileSync(new URL('./schema.sql',import.meta.url),'utf8');
assert.match(worker,/approved_revision=revision/,'Only latest approved revision may publish');
assert.match(worker,/status='approved'/,'Publishing must require approval');
assert.match(worker,/RETURNING id,title/,'Publish must atomically claim entries');
assert.match(worker,/Africa\/Lagos/);
assert.match(worker,/async scheduled\(/);
assert.match(worker,/status='draft'/,'Editing must revoke approval');
assert.match(worker,/ids\.length>100/,'Bulk approval limit');
assert.match(schema,/publish_date TEXT NOT NULL UNIQUE/);
assert.match(schema,/UNIQUE\(entry_id,destination\)/);
for(const key of ['id="month"','id="calendar"','id="editor"','id="approve"','id="date"','id="scripture"'])assert.ok(html.includes(key),key);
assert.ok(!html.includes('EDITOR_TOKEN='));
assert.ok(html.includes("credentials:'same-origin'"));
assert.ok(!html.includes('innerHTML='));
new vm.Script(html.match(/<script type="module">([\s\S]*?)<\/script>/)[1],{filename:'editor.js'});
console.log('PASS Daily Manna editorial UI, approval invariants, schema and browser script syntax');
