import assert from 'node:assert/strict';
import {facebookReady,devotionalCaption,publishToFacebook} from './facebook-publisher.mjs';
const entry={publish_date:'2026-11-01',title:'The Word',scripture:'John 1:1',body:'Read and reflect',prayer:'Give us wisdom'};
const env={FACEBOOK_PAGE_ID:'12345',FACEBOOK_PAGE_TOKEN:'server-only-token',MANNA_PUBLIC_ORIGIN:'https://dailyword.heavenlykey.org'};
assert.equal(facebookReady({}),false);
assert.equal(facebookReady(env),true);
const caption=devotionalCaption(entry,env.MANNA_PUBLIC_ORIGIN);
assert.ok(caption.text.includes('Prayer: Give us wisdom'));
assert.equal(caption.link,'https://dailyword.heavenlykey.org/?date=2026-11-01');
assert.throws(()=>devotionalCaption({...entry,publish_date:'invalid'},env.MANNA_PUBLIC_ORIGIN));
assert.throws(()=>devotionalCaption(entry,'http://unsafe.invalid'));
let called=0;
const fake=async(url,opts)=>{
 called++;
 assert.equal(url,'https://graph.facebook.com/v26.0/12345/feed');
 assert.equal(opts.headers.authorization,'Bearer server-only-token');
 assert.ok(opts.body.get('message').includes('John 1:1'));
 return new Response(JSON.stringify({id:'12345_789'}),{status:200,headers:{'content-type':'application/json'}});
};
const result=await publishToFacebook(entry,env,fake);
assert.equal(result.provider_post_id,'12345_789');
assert.equal(result.with_picture,false);
assert.equal(called,1);
const png=new Uint8Array([137,80,78,71,13,10,26,10,1]);
const pictureEnv={...env,MANNA_IMAGES:{async get(){return {async arrayBuffer(){return png.buffer}}}}};
await publishToFacebook({...entry,picture_object_key:'post-banners/abc',picture_content_type:'image/png'},pictureEnv,async(url,opts)=>{
 assert.ok(url.endsWith('/photos'));
 assert.ok(opts.body instanceof FormData);
 assert.ok(opts.body.get('source') instanceof Blob);
 assert.ok(opts.body.get('caption').includes('Read and reflect'));
 return new Response(JSON.stringify({id:'321'}),{status:200,headers:{'content-type':'application/json'}});
});
await assert.rejects(publishToFacebook(entry,env,async()=>new Response(JSON.stringify({error:{message:'no access'}}),{status:403})),/Facebook rejected publication/);
console.log('PASS Facebook Page publisher: caption, URL safety, photo, authorization and errors');
