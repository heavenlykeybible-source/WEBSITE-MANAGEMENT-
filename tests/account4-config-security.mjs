import assert from 'node:assert/strict';
import fs from 'node:fs';
const config=fs.readFileSync(new URL('../wrangler.toml',import.meta.url),'utf8');
const workflow=fs.readFileSync(new URL('../.github/workflows/account4-security-checks.yml',import.meta.url),'utf8');
const pkg=JSON.parse(fs.readFileSync(new URL('../package.json',import.meta.url),'utf8'));
const must=(ok,message)=>assert.ok(ok,message);
must(/^name\s*=\s*"website-management"\s*$/m.test(config),'Worker name must stay protected');
must(/^main\s*=\s*"control-room-worker\.js"\s*$/m.test(config),'Deployment entry must stay the reviewed Worker');
must(/^SIGNUP_OPEN\s*=\s*"false"\s*$/m.test(config),'Public signup must remain closed until intentional owner approval');
must(/^PROTECTED_WORKERS\s*=\s*"website-management"\s*$/m.test(config),'Control Room Worker must remain protected');
for(const binding of ['DB','FILES','AI'])must(new RegExp('binding\\s*=\\s*"'+binding+'"').test(config),'Missing binding '+binding);
must(/^on:\s*\n\s+pull_request:\s*\n\s+push:\s*\n\s+branches:\s*\n\s+- main\s*$/m.test(workflow),'Security checks must run on every PR and main push');
must(/^permissions:\s*\n\s+contents:\s*read\s*$/m.test(workflow),'Security workflow must use read-only repository permissions');
must(!/\b(?:wrangler deploy|npm run deploy|cloudflare\/wrangler-action)\b/i.test(workflow),'Security workflow must not deploy');
must(!/^\s*(?:id-token|actions|deployments|packages):\s*write\b/m.test(workflow),'Security workflow cannot request write permissions');
must(!/\bsecrets\.[A-Za-z_]+/.test(workflow),'Non-deploying checks must not read deployment secrets');
must(pkg.private===true,'Project must remain private as an npm package');
must(pkg.scripts['prepare:account4-release']?.includes('apply-reviewed-account4-upgrade'),'Release preparation must preserve integrity-verified upgrade');
must(!/wrangler deploy|npm run deploy/.test(pkg.scripts['prepare:account4-release']),'Release preparation must not deploy');
console.log('PASS Account 4 protected Worker config, bindings, read-only CI and approval-only release guards');
